export const getRankName = (points, lang) => {
  let rank = RANK_STEPS[0];
  for (const r of RANK_STEPS) {
    if (points >= r.min) rank = r;
    else break;
  }
  return lang === 'hr' ? rank.hr : rank.en;
};

